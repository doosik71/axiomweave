"""Lean 4 export of kernel-accepted certificates (interop-spec §3).

The exporter is untrusted. It checks the bundle with the kernel first, decodes
it with the kernel's own decoder, and recomputes the conclusion of every
derivation node to write each Lean proof term with all implicit arguments
given explicitly (`@`). Whether that recomputation is right is what the Lean
check reveals.
"""

from collections.abc import Mapping
from dataclasses import dataclass
from importlib import metadata

from axiomweave.kernel import REJECTED, KernelReport, check_bundle
from axiomweave.kernel.certificate import (
    DEFAULT_LIMITS,
    PROP_RESULT,
    Declaration,
    Node,
    Prop,
    PropTable,
    check_bundle_header,
    decode_declaration,
    parse_json,
)
from axiomweave.kernel.errors import Diagnostic

Delta = tuple[str, ...]  # sorts of the bound variables in scope, outermost first
Signature = dict[str, tuple[str, ...]]  # schematic variable -> argument sorts
Context = dict[str, tuple[Prop, int]]  # hypothesis -> (proposition, depth)

# --- standard axioms (interop-spec §3.6); changing this text bumps the exporter ---

_NAT = "arith.Nat"
# Standard sort and constants: (argument sorts, result sort, Lean definition).
_ARITH_DEFINITIONS: dict[str, tuple[tuple[str, ...], str, str]] = {
    "arith.zero": ((), _NAT, "_root_.Nat.zero"),
    "arith.succ": ((_NAT,), _NAT, "_root_.Nat.succ"),
    "arith.add": ((_NAT, _NAT), _NAT, "_root_.Nat.add"),
    "arith.mul": ((_NAT, _NAT), _NAT, "_root_.Nat.mul"),
}
# Proofs of the standard axioms; the statements are rendered from the bundle,
# whose axiom hashes the kernel has matched against the allow list.
_STANDARD_PROOFS: dict[str, str] = {
    "classical.em": "(_root_.Classical.em «P»)",
    "arith.succ_ne_zero": "(fun x0 => _root_.Nat.succ_ne_zero x0)",
    "arith.succ_inj": "(fun _ _ h => _root_.Nat.succ.inj h)",
    "arith.add_zero": "(fun _ => _root_.rfl)",
    "arith.add_succ": "(fun _ _ => _root_.rfl)",
    "arith.mul_zero": "(fun _ => _root_.rfl)",
    "arith.mul_succ": "(fun _ _ => _root_.rfl)",
    "arith.induction": "(fun h0 hs x0 => @_root_.Nat.rec «P» h0 hs x0)",
}


class ExportError(Exception):
    """The kernel rejected the bundle, so nothing is exported."""

    def __init__(self, diagnostic: Diagnostic) -> None:
        super().__init__(f"{diagnostic.code} at {diagnostic.path}: {diagnostic.message}")
        self.diagnostic = diagnostic


@dataclass(frozen=True)
class LeanExport:
    text: str
    report: KernelReport
    exported: tuple[str, ...]  # declarations written to the Lean file
    skipped: tuple[str, ...]  # declarations the kernel rejected


def export_lean(data: bytes, allowed_axioms: Mapping[str, str]) -> LeanExport:
    """Check a certificate with the kernel and translate its accepted declarations."""
    report = check_bundle(data, allowed_axioms)
    if not report.bundle_ok:
        assert report.bundle_error is not None
        raise ExportError(report.bundle_error)

    bundle = check_bundle_header(parse_json(data, DEFAULT_LIMITS), DEFAULT_LIMITS)
    table = PropTable()
    decls = [
        decode_declaration(value, i, table, bundle["fragment"])
        for i, value in enumerate(bundle["declarations"])
    ]
    accepted = [d for d, r in zip(decls, report.results, strict=True) if r.status != REJECTED]
    skipped = tuple(r.name for r in report.results if r.status == REJECTED)

    standard = {
        d.name
        for d in accepted
        if d.kind == "axiom"
        and d.name in _STANDARD_PROOFS
        and allowed_axioms.get(d.name) == d.computed_hash
    }
    writer = _Writer(table, uses_arith=any(name.startswith("arith.") for name in standard))
    blocks = [writer.declaration(d, d.name in standard) for d in accepted]

    header = [
        (
            f"-- Generated by AxiomWeave {_version()} from {bundle['theory']} "
            f"(bundle {bundle['bundle_hash']})"
        ),
        "-- Lean 4 core only. This file is a cross-check, not a source of truth.",
        "set_option autoImplicit false",
    ]
    text = "\n\n".join(["\n".join(header), *blocks]) + "\n"
    return LeanExport(text, report, tuple(d.name for d in accepted), skipped)


def _version() -> str:
    try:
        return metadata.version("axiomweave")
    except metadata.PackageNotFoundError:
        return "unknown"


def _name(name: str) -> str:
    """`a.b.c` -> `«a».«b».«c»` (interop-spec §3.3)."""
    return ".".join(f"«{part}»" for part in name.split("."))


def _hyp(name: str) -> str:
    return f"«h_{name}»"


def _var(depth: int) -> str:
    return f"x{depth}"


def _apply(head: str, args: list[str]) -> str:
    return f"({head} {' '.join(args)})" if args else head


class _Writer:
    def __init__(self, table: PropTable, uses_arith: bool) -> None:
        self.table = table
        self.uses_arith = uses_arith
        self.consts: dict[str, tuple[tuple[str, ...], str]] = {}
        self.statements: dict[str, tuple[Prop, Signature]] = {}
        self.params: Signature = {}  # schematic parameters of the current declaration

    # --- declarations (interop-spec §3.5) -----------------------------------------

    def declaration(self, d: Declaration, standard: bool) -> str:
        if d.kind == "sort":
            if self.uses_arith and d.name == _NAT:
                return f"abbrev {_name(d.name)} : Type := _root_.Nat"
            return f"axiom {_name(d.name)} : Type"
        if d.kind == "const":
            self.consts[d.name] = (d.args, d.result)
            result = "Prop" if d.result == PROP_RESULT else _name(d.result)
            type_ = " → ".join([*(_name(s) for s in d.args), result])
            definition = _ARITH_DEFINITIONS.get(d.name)
            if self.uses_arith and definition and definition[:2] == (d.args, d.result):
                return f"abbrev {_name(d.name)} : {type_} := {definition[2]}"
            return f"axiom {_name(d.name)} : {type_}"

        assert d.statement is not None
        self.params = self.signature(d.statement)
        self.statements[d.name] = (d.statement, self.params)
        binders = "".join(f" ({_name(p)} : {self._param_type(s)})" for p, s in self.params.items())
        statement = self.prop(d.statement, ())
        if d.kind == "axiom" and not standard:
            return f"axiom {_name(d.name)}{binders} :\n    {statement}"
        if d.kind == "axiom":
            proof = _STANDARD_PROOFS[d.name]
        else:
            assert d.proof is not None
            proof = self.proof((), {}, d.proof)[1]
        return f"theorem {_name(d.name)}{binders} :\n    {statement} :=\n  {proof}"

    @staticmethod
    def _param_type(sorts: tuple[str, ...]) -> str:
        return " → ".join([*(_name(s) for s in sorts), "Prop"])

    def signature(self, statement: Prop) -> Signature:
        """Schematic variables in order of first occurrence, with argument sorts."""
        result: Signature = {}

        def go(p: Prop, delta: Delta) -> None:
            node = self.table.nodes[p]
            tag = node[0]
            if tag == "atom":
                result.setdefault(node[1], ())
            elif tag == "pvar":
                result.setdefault(node[1], tuple(self.sort_of(a, delta) for a in node[2]))
            elif tag in ("and", "or", "imp"):
                go(node[1], delta)
                go(node[2], delta)
            elif tag in ("forall", "exists"):
                go(node[2], (*delta, node[1]))

        go(statement, ())
        return result

    # --- propositions and terms (interop-spec §3.4) --------------------------------

    def sort_of(self, term: Prop, delta: Delta) -> str:
        node = self.table.nodes[term]
        if node[0] == "var":
            return delta[-1 - node[1]]
        return self.consts[node[1]][1]

    def term(self, term: Prop, delta: Delta) -> str:
        node = self.table.nodes[term]
        if node[0] == "var":
            return _var(len(delta) - 1 - node[1])
        return _apply(_name(node[1]), [self.term(a, delta) for a in node[2]])

    def prop(self, prop: Prop, delta: Delta) -> str:
        node = self.table.nodes[prop]
        tag = node[0]
        if tag == "false":
            return "False"
        if tag == "atom":
            # Schematic variables that are not parameters of the declaration occur
            # only inside the proof; they are uniformly replaced by True (§3.5).
            return _name(node[1]) if self.params.get(node[1]) == () else "True"
        if tag == "pvar":
            sorts = tuple(self.sort_of(a, delta) for a in node[2])
            if self.params.get(node[1]) != sorts:
                return "True"
            return _apply(_name(node[1]), [self.term(a, delta) for a in node[2]])
        if tag == "pred":
            return _apply(_name(node[1]), [self.term(a, delta) for a in node[2]])
        if tag in ("forall", "exists"):
            quantifier = "∀" if tag == "forall" else "∃"
            body = self.prop(node[2], (*delta, node[1]))
            return f"({quantifier} ({_var(len(delta))} : {_name(node[1])}), {body})"
        if tag == "eq":
            sort = _name(self.sort_of(node[1], delta))
            return f"(@Eq {sort} {self.term(node[1], delta)} {self.term(node[2], delta)})"
        symbol = {"and": "∧", "or": "∨", "imp": "→"}[tag]
        return f"({self.prop(node[1], delta)} {symbol} {self.prop(node[2], delta)})"

    def _lambda(self, sorts: tuple[str, ...], delta: Delta, body: str) -> str:
        binders = " ".join(
            f"({_var(len(delta) + i)} : {_name(sort)})" for i, sort in enumerate(sorts)
        )
        return f"(fun {binders} => {body})"

    # --- proofs (interop-spec §3.5) ---------------------------------------------------

    def proof(self, delta: Delta, gamma: Context, node: Node) -> tuple[Prop, str]:
        """The conclusion of an accepted derivation node and its Lean term."""
        table = self.table
        rule = node[0]

        def show(p: Prop, d: Delta = delta) -> str:
            return self.prop(p, d)

        if rule == "hyp":
            prop, depth = gamma[node[2]]
            return table.shift(prop, len(delta) - depth), _hyp(node[2])

        if rule == "and_i":
            a, left = self.proof(delta, gamma, node[2])
            b, right = self.proof(delta, gamma, node[3])
            return table.make(("and", a, b)), f"(@And.intro {show(a)} {show(b)} {left} {right})"

        if rule in ("and_e1", "and_e2"):
            premise, of = self.proof(delta, gamma, node[2])
            _, a, b = table.nodes[premise]
            field = "left" if rule == "and_e1" else "right"
            return (a if rule == "and_e1" else b), f"(@And.{field} {show(a)} {show(b)} {of})"

        if rule == "or_i1":
            a, of = self.proof(delta, gamma, node[2])
            b = node[3]
            return table.make(("or", a, b)), f"(@Or.inl {show(a)} {show(b)} {of})"

        if rule == "or_i2":
            a = node[2]
            b, of = self.proof(delta, gamma, node[3])
            return table.make(("or", a, b)), f"(@Or.inr {show(a)} {show(b)} {of})"

        if rule == "or_e":
            _, _, of_node, left_name, left_node, right_name, right_node = node
            premise, of = self.proof(delta, gamma, of_node)
            _, a, b = table.nodes[premise]
            depth = len(delta)
            c, left = self.proof(delta, {**gamma, left_name: (a, depth)}, left_node)
            _, right = self.proof(delta, {**gamma, right_name: (b, depth)}, right_node)
            return c, (
                f"(@Or.elim {show(a)} {show(b)} {show(c)} {of} "
                f"(fun ({_hyp(left_name)} : {show(a)}) => {left}) "
                f"(fun ({_hyp(right_name)} : {show(b)}) => {right}))"
            )

        if rule == "imp_i":
            _, _, name, hyp, body_node = node
            c, body = self.proof(delta, {**gamma, name: (hyp, len(delta))}, body_node)
            return table.make(("imp", hyp, c)), f"(fun ({_hyp(name)} : {show(hyp)}) => {body})"

        if rule == "imp_e":
            fn_prop, fn = self.proof(delta, gamma, node[2])
            _, arg = self.proof(delta, gamma, node[3])
            return table.nodes[fn_prop][2], f"({fn} {arg})"

        if rule == "false_e":
            _, of = self.proof(delta, gamma, node[2])
            goal = node[3]
            return goal, f"(@False.elim {show(goal)} {of})"

        if rule == "all_i":
            _, _, sort, body_node = node
            c, body = self.proof((*delta, sort), gamma, body_node)
            return table.make(("forall", sort, c)), self._lambda((sort,), delta, body)

        if rule == "all_e":
            premise, of = self.proof(delta, gamma, node[2])
            term = node[3]
            conclusion = table.instantiate(table.nodes[premise][2], (term,))
            return conclusion, f"({of} {self.term(term, delta)})"

        if rule == "ex_i":
            _, _, prop, witness, of_node = node
            sort = self.sort_of(witness, delta)
            _, of = self.proof(delta, gamma, of_node)
            motive = self._lambda((sort,), delta, show(prop, (*delta, sort)))
            witness_text = self.term(witness, delta)
            return table.make(("exists", sort, prop)), (
                f"(@Exists.intro {_name(sort)} {motive} {witness_text} {of})"
            )

        if rule == "ex_e":
            _, _, of_node, name, body_node = node
            premise, of = self.proof(delta, gamma, of_node)
            _, sort, prop = table.nodes[premise]
            inner = (*delta, sort)
            c, body = self.proof(inner, {**gamma, name: (prop, len(inner))}, body_node)
            conclusion = table.lower(c, "$")
            motive = self._lambda((sort,), delta, show(prop, inner))
            x = _var(len(delta))
            return conclusion, (
                f"(@Exists.elim {_name(sort)} {motive} {show(conclusion)} {of} "
                f"(fun ({x} : {_name(sort)}) ({_hyp(name)} : {show(prop, inner)}) => {body}))"
            )

        if rule == "eq_refl":
            term = node[2]
            sort = _name(self.sort_of(term, delta))
            return table.make(("eq", term, term)), f"(@rfl {sort} {self.term(term, delta)})"

        if rule == "eq_e":
            _, _, eq_node, motive, of_node = node
            premise, eq = self.proof(delta, gamma, eq_node)
            _, left, right = table.nodes[premise]
            sort = self.sort_of(left, delta)
            _, of = self.proof(delta, gamma, of_node)
            motive_text = self._lambda((sort,), delta, show(motive, (*delta, sort)))
            return table.instantiate(motive, (right,)), (
                f"(@Eq.subst {_name(sort)} {motive_text} {self.term(left, delta)} "
                f"{self.term(right, delta)} {eq} {of})"
            )

        if rule in ("thm", "ax"):
            _, _, name, _, subst = node
            statement, signature = self.statements[name]
            args = []
            for key, sorts in signature.items():
                if key in subst:
                    params, body = subst[key]
                    value = show(body, (*delta, *params))
                    args.append(self._lambda(params, delta, value) if params else value)
                elif self.params.get(key) == sorts:
                    args.append(_name(key))
                else:
                    args.append(self._lambda(sorts, delta, "True") if sorts else "True")
            return table.substitute(statement, subst), _apply(_name(name), args)

        raise AssertionError(f"unhandled rule {rule!r}")
