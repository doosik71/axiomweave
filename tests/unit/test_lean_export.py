"""Lean 4 export of kernel-accepted certificates (interop-spec §3).

Lean itself runs only where `lean` is installed; otherwise these tests check the
structure of the generated text.
"""

import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

from axiomweave import Theory
from axiomweave.backends.lean import ExportError, export_lean
from axiomweave.kernel import STANDARD_AXIOMS
from axiomweave.kernel.axioms import CLASSICAL_EM
from axiomweave.lib.arithmetic.peano import arith
from axiomweave.lib.logic.propositional import propositional
from tests.helpers import (
    all_i,
    and_,
    and_e1,
    and_i,
    atom,
    axiom,
    bundle,
    encode,
    forall,
    hyp,
    imp,
    imp_e,
    imp_i,
    l1_bundle,
    pvar,
    ref,
    sort,
    theorem,
    var,
)

P, Q, R = atom("P"), atom("Q"), atom("R")


def export(obj: object) -> str:
    return export_lean(encode(obj), STANDARD_AXIOMS).text


def blocks(text: str) -> list[str]:
    """The declaration blocks after the three header lines."""
    return text.split("\n\n")[1:]


IMP_TRANS = theorem(
    "demo.logic.imp_trans",
    imp(imp(P, Q), imp(Q, R), P, R),
    imp_i(
        "h1",
        imp(P, Q),
        imp_i("h2", imp(Q, R), imp_i("h3", P, imp_e(hyp("h2"), imp_e(hyp("h1"), hyp("h3"))))),
    ),
)


def test_spec_example_propositional() -> None:
    text = export(bundle(IMP_TRANS))
    assert text.startswith("-- Generated by AxiomWeave ")
    assert "set_option autoImplicit false\n" in text
    assert blocks(text) == [
        (
            "theorem «demo».«logic».«imp_trans» («P» : Prop) («Q» : Prop) («R» : Prop) :\n"
            "    ((«P» → «Q») → ((«Q» → «R») → («P» → «R»))) :=\n"
            "  (fun («h_h1» : («P» → «Q»)) => (fun («h_h2» : («Q» → «R»)) => "
            "(fun («h_h3» : «P») => («h_h2» («h_h1» «h_h3»)))))\n"
        )
    ]


def test_spec_example_first_order() -> None:
    U = "demo.fol.U"
    body = and_(pvar("P", var(0)), pvar("Q", var(0)))
    statement = imp(forall(U, body), forall(U, pvar("P", var(0))))
    proof = imp_i(
        "h1",
        forall(U, body),
        all_i(U, and_e1({"rule": "all_e", "of": hyp("h1"), "term": var(0)})),
    )
    text = export(l1_bundle(sort(U), theorem("demo.fol.all_and_left", statement, proof)))
    u = "«demo».«fol».«U»"
    assert blocks(text) == [
        f"axiom {u} : Type",
        (
            f"theorem «demo».«fol».«all_and_left» («P» : {u} → Prop) («Q» : {u} → Prop) :\n"
            f"    ((∀ (x0 : {u}), ((«P» x0) ∧ («Q» x0))) → (∀ (x0 : {u}), («P» x0))) :=\n"
            f"  (fun («h_h1» : (∀ (x0 : {u}), ((«P» x0) ∧ («Q» x0)))) => (fun (x0 : {u}) => "
            "(@And.left («P» x0) («Q» x0) («h_h1» x0))))\n"
        ),
    ]


def certificate(thy: Theory) -> bytes:
    assert thy.check().ok
    with tempfile.TemporaryDirectory() as tmp:
        return thy.export(Path(tmp) / "bundle.axwp").read_bytes()


def test_output_is_deterministic() -> None:
    data = certificate(propositional)
    assert export_lean(data, STANDARD_AXIOMS).text == export_lean(data, STANDARD_AXIOMS).text


IDENTITY = theorem("demo.logic.id", imp(P, P), imp_i("h", P, hyp("h")))


def test_schematic_variables_outside_the_statement_become_true() -> None:
    # Q → Q, proved through id instantiated at R → R, which the statement never mentions.
    proof = imp_i(
        "h",
        Q,
        and_e1(and_i(hyp("h"), ref("thm", IDENTITY, {"P": imp(R, R)}))),
    )
    text = export(bundle(IDENTITY, theorem("demo.logic.q", imp(Q, Q), proof)))
    assert blocks(text)[1] == (
        "theorem «demo».«logic».«q» («Q» : Prop) :\n"
        "    («Q» → «Q») :=\n"
        "  (fun («h_h» : «Q») => (@And.left «Q» ((True → True) → (True → True)) "
        "(@And.intro «Q» ((True → True) → (True → True)) «h_h» («demo».«logic».«id» (True → True)))))\n"
    )


def test_unsubstituted_parameter_is_passed_through() -> None:
    text = export(bundle(IDENTITY, theorem("demo.logic.id2", imp(P, P), ref("thm", IDENTITY))))
    assert blocks(text)[1].endswith("  («demo».«logic».«id» «P»)\n")


def test_user_axiom_and_classical_em() -> None:
    user = axiom("demo.logic.k", imp(P, Q))
    em = {**CLASSICAL_EM, "hash": STANDARD_AXIOMS["classical.em"]}
    use = theorem(
        "demo.logic.use",
        imp(P, Q),
        ref("ax", user),
        axioms=("demo.logic.k",),
    )
    policy = {**STANDARD_AXIOMS, "demo.logic.k": user["hash"]}
    text = export_lean(encode(bundle(em, user, use)), policy).text
    em_block, user_block, use_block = blocks(text)
    assert em_block == (
        "theorem «classical».«em» («P» : Prop) :\n"
        "    («P» ∨ («P» → False)) :=\n"
        "  (_root_.Classical.em «P»)"
    )
    assert user_block == "axiom «demo».«logic».«k» («P» : Prop) («Q» : Prop) :\n    («P» → «Q»)"
    assert use_block.endswith("  («demo».«logic».«k» «P» «Q»)\n")


def test_arith_uses_lean_naturals() -> None:
    text = export_lean(certificate(arith), STANDARD_AXIOMS).text
    assert "abbrev «arith».«Nat» : Type := _root_.Nat" in text
    assert "abbrev «arith».«succ» : «arith».«Nat» → «arith».«Nat» := _root_.Nat.succ" in text
    assert "axiom «arith»" not in text
    assert "theorem «arith».«induction» («P» : «arith».«Nat» → Prop) :" in text
    assert "@_root_.Nat.rec «P» h0 hs x0" in text
    assert "theorem «arith».«add_assoc» :" in text


def test_nat_without_standard_axioms_stays_abstract() -> None:
    nat = sort("arith.Nat")
    text = export(l1_bundle(nat, theory="demo.fol"))
    assert blocks(text) == ["axiom «arith».«Nat» : Type\n"]


def test_rejected_bundle_is_not_exported() -> None:
    obj = bundle(IDENTITY)
    obj["bundle_hash"] = "sha256:" + "0" * 64
    with pytest.raises(ExportError) as info:
        export_lean(encode(obj), STANDARD_AXIOMS)
    assert info.value.diagnostic.code == "E_HASH_MISMATCH"


def test_rejected_declarations_are_skipped() -> None:
    bad = theorem("demo.logic.bad", Q, imp_i("h", P, hyp("h")))
    result = export_lean(encode(bundle(IDENTITY, bad)), STANDARD_AXIOMS)
    assert result.exported == ("demo.logic.id",)
    assert result.skipped == ("demo.logic.bad",)
    assert "bad" not in result.text


@pytest.mark.skipif(shutil.which("lean") is None, reason="lean is not installed")
def test_lean_accepts_exported_libraries(tmp_path: Path) -> None:
    certificates = {
        "arith": certificate(arith),
        "propositional": certificate(propositional),
        "imp_trans": encode(bundle(IMP_TRANS)),
    }
    for name, data in certificates.items():
        path = tmp_path / f"{name}.lean"
        path.write_text(export_lean(data, STANDARD_AXIOMS).text, encoding="utf-8")
        lean = shutil.which("lean")
        assert lean is not None
        result = subprocess.run([lean, str(path)], capture_output=True, text=True, check=False)
        assert result.returncode == 0, result.stdout + result.stderr
